import { chromium } from "playwright";
import { mkdtempSync, rmSync } from "fs";
import { join } from "path";
import { tmpdir } from "os";
import { strict as assert } from "assert";
import { startServer } from "../src/server/server";
import { readStore, saveStore, withGraphLock } from "../src/storage";
import { setOrcaRunnerForTests } from "../src/orca";

const directory = mkdtempSync(join(tmpdir(), "dagdo-orca-browser-"));
const previous = process.env.DAGDO_DATA_DIR;
process.env.DAGDO_DATA_DIR = directory;
let archived = false;
let workspace: any;
let failProjects = false, failOpen = false;
const calls: string[][] = [];
const projectNames = ["Sample project", "Billing service", "Customer portal", "Documentation site", "Mobile application", "Shared infrastructure with a long project name"];
setOrcaRunnerForTests(async args => {
  calls.push(args);
  switch (args.slice(0, 2).join(" ")) {
    case "project list":
      await new Promise(r => setTimeout(r, 200));
      if (failProjects) throw new Error("Fake project list failure");
      return { projects: projectNames.map((displayName, index) => ({ id: `project-${index}`, displayName })) };
    case "project setups": return { setups: projectNames.map((_, index) => ({ id: `setup-${index}`, projectId: `project-${index}`, repoId: "repo", hostId: "local", kind: "git", setupState: "ready", path: index ? join(directory, "a very long nested directory name for checking truncation", String(index)) : directory })) };
    case "repo list": return { repos: [{ id: "repo", worktreeBaseRef: "main" }] };
    case "repo search-refs": return { refs: ["main", "origin/main"] };
    case "worktree create":
      await new Promise(r => setTimeout(r, 150));
      workspace = { id: "repo::" + directory, identity: { key: "wt2:local:browser" }, hostId: "local", repoId: "repo", projectId: "project", path: directory, displayName: args[args.indexOf("--name") + 1], branch: "feature/browser" };
      return { worktree: workspace };
    case "worktree show": return { worktree: { ...workspace, isArchived: archived } };
    case "terminal list": return { terminals: [{ handle: "browser-terminal" }] };
    case "terminal switch":
      if (failOpen) throw new Error("Fake open failure");
      return { ok: true };
    default: throw new Error("Unexpected fake Orca command: " + args.join(" "));
  }
});
await withGraphLock(async () => {
  const store = readStore();
  store.projects[0]!.tasks = [{ id: "abcdef", title: "Implement sample task", progress: "ready", createdAt: new Date().toISOString(), doneAt: null }];
  await saveStore(store);
});
const server = await startServer({ preferredPort: 0 });
const browser = await chromium.launch({ headless: true, executablePath: process.env.DAGDO_BROWSER_EXECUTABLE });
try {
  const context = await browser.newContext(); const page = await context.newPage();
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto(server.url);
  const list = page.locator('aside[aria-label="Actionable tasks"]');
  assert.equal(await list.getByRole("combobox").count(), 0);
  assert.equal(await list.getByRole("button", { name: /Mark .* as done/ }).count(), 0);
  const taskButton = list.getByRole("button", { name: "Implement sample task", exact: true });
  await taskButton.waitFor();
  const viewport = page.locator(".react-flow__viewport");
  await page.waitForTimeout(400);
  await page.getByRole("button", { name: "Zoom out" }).click();
  await page.waitForTimeout(400);
  const beforeFocus = await viewport.getAttribute("style");
  await taskButton.click();
  await page.waitForTimeout(500);
  assert.notEqual(await viewport.getAttribute("style"), beforeFocus);
  assert.equal(await page.getByRole("dialog", { name: "Task", exact: true }).count(), 0);
  const nodeBox = await page.locator('.react-flow__node[data-id="abcdef"]').boundingBox();
  const mapBox = await page.locator(".react-flow").boundingBox();
  assert(nodeBox && mapBox);
  assert(Math.abs(nodeBox.x + nodeBox.width / 2 - mapBox.x - mapBox.width / 2) < 3);
  assert(Math.abs(nodeBox.y + nodeBox.height / 2 - mapBox.y - mapBox.height / 2) < 3);
  await taskButton.dblclick();
  const taskDialog = page.getByRole("dialog", { name: "Task", exact: true });
  await taskDialog.waitFor();
  assert.equal(await taskDialog.getByText("Tags", { exact: true }).count(), 0);
  await taskDialog.getByText(/^Created on /).waitFor();
  await taskDialog.getByRole("button", { name: "Close", exact: true }).click();
  const createButton = list.getByRole("button", { name: "Create workspace", exact: true });
  const resizeList = async (delta: number) => {
    const box = await list.getByRole("separator").boundingBox();
    await page.mouse.move(box!.x + 1, box!.y + 100); await page.mouse.down();
    await page.mouse.move(box!.x + 1 + delta, box!.y + 100); await page.mouse.up();
  };
  const taskBox = await taskButton.boundingBox(), createBox = await createButton.boundingBox();
  assert(taskBox && createBox);
  assert(createBox.height <= 24);
  assert(createBox.x > taskBox.x && createBox.y < taskBox.y + taskBox.height);
  await resizeList(-100);
  const narrowCreateBox = await createButton.boundingBox(), narrowTaskBox = await taskButton.boundingBox();
  assert(narrowCreateBox && narrowTaskBox);
  assert(narrowCreateBox.y >= narrowTaskBox.y + narrowTaskBox.height);
  await page.screenshot({ path: join(directory, "orca-list-narrow.png"), animations: "disabled" });
  await resizeList(100);
  await page.screenshot({ path: join(directory, "orca-list-wide.png"), animations: "disabled" });
  await page.evaluate(`window.dialogFrames = []; (function sample() {
    window.dialogFrames.push([...document.querySelectorAll('[role="dialog"]')].map(d => d.querySelector("h2")?.textContent).join("|"));
    if (window.dialogFrames.length < 60) requestAnimationFrame(sample);
  })()`);
  await createButton.click();
  const dialog = page.getByRole("dialog", { name: "Create workspace", exact: true });
  await dialog.waitFor();
  await page.waitForFunction("window.dialogFrames.length >= 60");
  const frames = await page.evaluate("window.dialogFrames") as string[];
  assert(frames.some(frame => frame.includes("Create workspace")));
  assert(frames.every(frame => frame === "" || frame === "Create workspace"), frames.join(","));
  const createSubmit = dialog.getByRole("button", { name: "Create workspace", exact: true });
  const search = dialog.getByLabel("Search projects");
  const projectSelect = dialog.getByRole("combobox", { name: "Project", exact: true });
  await search.waitFor();
  await page.waitForFunction("document.activeElement?.id === 'orca-project'");
  assert.equal(await projectSelect.inputValue(), "");
  assert.equal(await projectSelect.locator("option").count(), 7);
  assert(await createSubmit.isDisabled());
  await dialog.getByText("Advanced settings", { exact: true }).click();
  const dialogBox = await dialog.boundingBox();
  assert(dialogBox && dialogBox.y >= 0 && dialogBox.y + dialogBox.height <= page.viewportSize()!.height);
  assert(await dialog.locator("form > div").first().evaluate(element => element.scrollWidth <= element.clientWidth));
  await page.screenshot({ path: join(directory, "orca-create-advanced.png"), animations: "disabled" });
  await search.fill("zzz");
  await dialog.getByText("No projects match this search.").waitFor();
  await search.fill("billing");
  assert.equal(await projectSelect.locator("option").count(), 2);
  await search.fill("");
  await projectSelect.selectOption("setup-0");
  assert.equal(await dialog.getByLabel("Branch from").inputValue(), "main");
  assert(await createSubmit.isEnabled());
  await dialog.getByLabel("Workspace name", { exact: true }).fill("Browser workspace");
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  const taskPopup = page.getByRole("dialog", { name: "Task", exact: true });
  await taskPopup.waitFor();
  assert.equal(await page.getByRole("dialog").count(), 1);
  await taskPopup.getByRole("button", { name: "Close", exact: true }).click();
  await taskPopup.waitFor({ state: "hidden" });
  await createButton.click();
  await dialog.waitFor();
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await page.getByRole("dialog").count(), 0);
  await createButton.click();
  await dialog.waitFor();
  await dialog.getByRole("button", { name: "Back to task", exact: true }).click();
  await taskPopup.waitFor();
  await taskPopup.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor();
  assert.equal(await page.getByRole("dialog").count(), 1);
  await search.waitFor();
  await page.keyboard.press("Escape");
  await taskPopup.waitFor();
  assert.equal(await page.getByRole("dialog").count(), 1);
  await taskPopup.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor();
  await search.waitFor();
  await dialog.getByRole("button", { name: "Back to task", exact: true }).click();
  await taskPopup.waitFor();
  failProjects = true;
  await taskPopup.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor();
  await dialog.getByRole("alert").waitFor();
  assert.equal(await dialog.getByText(/No ready local Git projects/).count(), 0);
  failProjects = false;
  await dialog.getByRole("button", { name: "Back to task", exact: true }).click();
  await taskPopup.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor();
  await search.waitFor();
  await projectSelect.selectOption("setup-0");
  for (const mode of ["light", "dark"]) {
    await page.evaluate(`document.documentElement.classList.toggle("dark", ${mode === "dark"})`);
    await page.screenshot({ path: join(directory, `orca-create-${mode}.png`), animations: "disabled" });
  }
  await dialog.getByLabel("Workspace name", { exact: true }).fill("Browser workspace");
  await dialog.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await page.getByRole("dialog").count(), 0);
  await list.locator('img[alt="Orca"]').waitFor();
  await page.locator('.react-flow__node[data-id="abcdef"] img[alt="Orca"]').waitFor();
  assert(await list.locator('img[alt="Orca"]').evaluate((img: any) => img.complete && img.naturalWidth > 0));
  assert.equal(calls.filter(args => args[0] === "worktree" && args[1] === "create").length, 1);
  assert(calls.some(args => args[0] === "terminal" && args[1] === "switch"));
  const openWorkspace = list.getByRole("button", { name: "Open Browser workspace in Orca", exact: true });
  const openedBefore = calls.filter(args => args[0] === "terminal" && args[1] === "switch").length;
  const workspaceBox = await openWorkspace.boundingBox(), linkedTaskBox = await taskButton.boundingBox();
  assert(workspaceBox && linkedTaskBox);
  assert(workspaceBox.x > linkedTaskBox.x && workspaceBox.y < linkedTaskBox.y + linkedTaskBox.height);
  await page.screenshot({ path: join(directory, "orca-list-linked.png"), animations: "disabled" });
  await openWorkspace.click();
  await page.waitForFunction(`document.querySelector('[aria-label="Open Browser workspace in Orca"]')?.disabled === false`);
  assert.equal(calls.filter(args => args[0] === "terminal" && args[1] === "switch").length, openedBefore + 1);
  assert.equal(await page.getByRole("dialog", { name: "Task", exact: true }).count(), 0);
  await taskButton.dblclick();
  await page.getByRole("dialog", { name: "Task", exact: true }).waitFor();
  await page.getByRole("button", { name: "Open in Orca", exact: true }).waitFor({ state: "visible" });
  assert.equal(await page.locator("#task-progress").inputValue(), "in_progress");
  archived = true;
  await page.getByRole("button", { name: "Refresh workspace", exact: true }).click();
  const unlink = page.getByRole("button", { name: "Unlink and return to Ready", exact: true });
  await unlink.waitFor(); page.once("dialog", d => d.accept()); await unlink.click();
  await page.waitForFunction("document.querySelector('#task-progress')?.value === 'ready'");
  archived = false; failOpen = true;
  await taskPopup.getByRole("button", { name: "Create workspace", exact: true }).click();
  await dialog.waitFor();
  await search.waitFor();
  await projectSelect.selectOption("setup-0");
  await dialog.getByRole("button", { name: "Create workspace", exact: true }).click();
  await taskPopup.getByText(/Workspace created, but it could not be opened/).waitFor();
  assert.equal(await page.getByRole("dialog").count(), 1);
  assert.equal(calls.filter(args => args[0] === "worktree" && args[1] === "create").length, 2);
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log("Orca browser checks passed: list controls, wide and narrow list layout, list workspace open, single-click centering, double-click details, creation timestamp, logo, direct creation in one frame, single popup steps, project choice and search, project load failure, return to home after creation, themes, binding, In Progress, open, open failure, archive and unlink.");
  if (process.env.DAGDO_KEEP_BROWSER_ARTIFACTS === "1") console.log("Screenshots: " + directory);
} finally {
  await browser.close(); await server.stop(); setOrcaRunnerForTests();
  if (previous === undefined) delete process.env.DAGDO_DATA_DIR; else process.env.DAGDO_DATA_DIR = previous;
  if (process.env.DAGDO_KEEP_BROWSER_ARTIFACTS !== "1") rmSync(directory, { recursive: true, force: true });
}
