declare const document: { querySelector(selector: string): any; querySelectorAll(selector: string): { length: number } };
declare const DOMMatrix: new (transform: string) => { a: number };
declare function getComputedStyle(element: unknown): { transform: string };
import { strict as assert } from "assert";
import { mkdtempSync, rmSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { chromium } from "playwright";
import { startServer } from "../src/server/server";

const directory = mkdtempSync(join(tmpdir(), "dagdo-backlog-browser-"));
const previous = process.env.DAGDO_DATA_DIR;
process.env.DAGDO_DATA_DIR = directory;
const server = await startServer({ preferredPort: 0 });
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.DAGDO_BROWSER_EXECUTABLE });
  for (const colorScheme of ["light", "dark"] as const) for (const mode of ["tree", "mindmap"]) {
    const created = await fetch(`${server.url}/api/projects`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ name: `${colorScheme} ${mode}` }) });
    const project = (await created.json() as any).project;
    const base = `${server.url}/api/projects/${project.id}`;
    const request = (path: string, method = "GET", body?: unknown) => fetch(base + path, { method, headers: { "Content-Type": "application/json", Origin: server.url }, body: body === undefined ? undefined : JSON.stringify(body) });
    const context = await browser.newContext({ colorScheme, viewport: { width: 1440, height: 900 } });
    await context.addInitScript(({ id, mode }) => { sessionStorage.setItem("dagdo-active-project", id); localStorage.setItem("dagdo-layout-mode", mode); }, { id: project.id, mode });
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(server.url);
    const add = page.getByRole("button", { name: "Add backlog task", exact: true });
    await add.waitFor();
    await page.waitForFunction(() => !(document.querySelector('[aria-label="Add backlog task"]') as any)?.disabled);
    // Embedded browsers can suppress native prompts. Backlog creation must not use them.
    await page.addInitScript(() => { (globalThis as any).prompt = () => { throw new Error("Native prompts are unavailable"); }; });
    await page.evaluate(() => { (globalThis as any).prompt = () => { throw new Error("Native prompts are unavailable"); }; });
    await add.click();
    const form = page.getByRole("form", { name: "New backlog task" });
    const title = form.getByRole("textbox", { name: "Backlog task title" });
    await title.waitFor();
    assert(await title.evaluate(e => e === e.ownerDocument.activeElement));
    assert(await form.getByRole("button", { name: "Add", exact: true }).isDisabled());
    await title.fill("Cancelled task");
    await form.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal((await (await request("/graph")).json() as any).tasks.length, 0);
    await add.click();
    await title.fill("Escaped task"); await title.press("Escape");
    assert.equal(await form.count(), 0);
    await add.click();
    await title.fill("  Backlog browser fixture  ");
    await page.route("**/tasks", route => route.abort());
    await title.press("Enter");
    await form.getByRole("alert").waitFor();
    assert.equal(await title.inputValue(), "  Backlog browser fixture  ");
    await page.unroute("**/tasks");
    await form.getByRole("button", { name: "Add", exact: true }).click();
    await form.waitFor({ state: "detached" });
    const section = page.getByRole("region", { name: "Backlog", exact: true });
    const row = section.getByRole("button", { name: "Backlog browser fixture", exact: true });
    await row.waitFor();
    assert.equal(await page.locator(".react-flow__node-task").count(), 0);
    const graph = await (await request("/graph")).json() as any;
    const task = graph.tasks[0];
    await row.click();
    assert(await page.getByRole("button", { name: "Done", exact: true }).isDisabled());
    await page.getByRole("textbox", { name: "Task notes" }).fill("Preserved browser note");
    await page.getByRole("button", { name: "Close", exact: true }).click();
    await page.waitForTimeout(150);
    await page.getByRole("button", { name: "Zoom In", exact: true }).click();
    const pane = page.locator(".react-flow__pane");
    const box = await pane.boundingBox(); assert(box);
    // Pan before dragging so screen-to-flow conversion must handle both transforms.
    await page.keyboard.down("Space");
    await page.mouse.move(box.x + 500, box.y + 450);
    await page.mouse.down(); await page.mouse.move(box.x + 540, box.y + 470, { steps: 8 }); await page.mouse.up();
    await page.keyboard.up("Space");
    await row.dragTo(pane, { targetPosition: { x: 600, y: 400 } });
    const node = page.locator(`.react-flow__node[data-id="${task.id}"]`);
    await node.waitFor();
    assert.equal(await row.count(), 0);
    let state = await (await request("/history")).json() as any;
    assert.equal(state.graph.tasks.length, 1);
    assert.equal(state.graph.tasks[0].progress, "ready");
    assert.equal(state.graph.tasks[0].notes, "Preserved browser note");
    assert(state.positions[mode][task.id]);
    const scale = await page.locator(".react-flow__viewport").evaluate(e => new DOMMatrix(getComputedStyle(e).transform).a);
    const nodeBox = await node.boundingBox(); assert(nodeBox);
    assert(Math.abs(nodeBox.x - (box.x + 600 - 140 * scale)) < 3);
    assert(Math.abs(nodeBox.y - (box.y + 400 - 50 * scale)) < 3);
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    await row.waitFor(); assert.equal(await node.count(), 0);
    await page.getByRole("button", { name: "Redo", exact: true }).click(); await node.waitFor();
    const other = (await (await request("/tasks", "POST", { title: "Prerequisite" })).json() as any).task;
    await request("/edges", "POST", { from: other.id, to: task.id });
    await page.waitForFunction(() => document.querySelectorAll(".react-flow__node-task").length === 2);
    await node.dblclick();
    const progress = page.getByRole("combobox", { name: "Task progress" });
    page.once("dialog", d => d.dismiss()); await progress.selectOption("backlog");
    assert.equal((await (await request("/graph")).json() as any).edges.length, 1);
    page.once("dialog", d => d.accept()); await progress.selectOption("backlog");
    await page.waitForFunction(() => (document.querySelector('[aria-label="Task progress"]') as any)?.value === "backlog");
    state = await (await request("/history")).json() as any;
    assert.equal(state.graph.edges.length, 0);
    await page.getByRole("button", { name: "Close", exact: true }).click(); await row.waitFor();
    assert.equal(await node.count(), 0);
    await page.getByRole("button", { name: "Undo", exact: true }).click(); await node.waitFor();
    assert.equal((await (await request("/graph")).json() as any).edges.length, 1);
    assert.deepEqual(errors, []);
    await context.close();
  }
  console.log("Backlog browser checks passed in both themes and layouts.");
} finally {
  await browser?.close(); await server.stop();
  if (previous === undefined) delete process.env.DAGDO_DATA_DIR; else process.env.DAGDO_DATA_DIR = previous;
  rmSync(directory, { recursive: true, force: true });
}
